import { existsSync } from "node:fs";
import { read } from "./lib.mjs";
import { gateResult } from "./config.mjs";
import {
  QUALITY_FILE,
  STATUS_DOC,
  STATUS_BEGIN,
  STATUS_END,
  FLOWS,
  CONTRACT_CASES,
  verifyChain,
  caseCount,
  renderStatusBlock,
} from "./quality-lib.mjs";

// @adr 001 - the status gate: the documented numbers ARE the derived numbers (BR-36)
//
// Runs immediately after quality:report and holds three copies to one source:
//   (a) .proto-forge/quality.json exists and parses — the derived facts are there
//   (b) the docs/STATUS.md block between the markers re-renders byte-identical
//       from quality.json — a hand-edited status is not a status
//   (c) the mirror facts in quality.json agree with the sources that actually
//       carry them: the registry case counts and the verify chain in
//       package.json
// No wall-clock and no tolerance windows: agreement or a red build.

const errors = [];
let quality = null;

if (!existsSync(QUALITY_FILE)) {
  errors.push(`${QUALITY_FILE} is missing — quality:report writes it during verify; run pnpm verify`);
} else {
  try {
    quality = JSON.parse(read(QUALITY_FILE));
  } catch {
    errors.push(`${QUALITY_FILE} is not parseable JSON — regenerate it with pnpm quality:report`);
  }
}

if (quality !== null) {
  // --- (b) the document block is the derivation, byte for byte ----------------
  if (!existsSync(STATUS_DOC)) {
    errors.push(`${STATUS_DOC} is missing — the standing quality document is part of the template`);
  } else {
    const body = read(STATUS_DOC);
    const begin = body.indexOf(STATUS_BEGIN);
    const end = body.indexOf(STATUS_END);
    if (begin === -1 || end === -1 || end < begin) {
      errors.push(`${STATUS_DOC}: the ${STATUS_BEGIN} … ${STATUS_END} markers are missing — the block between them is generated by pnpm quality:report`);
    } else if (body.slice(begin + STATUS_BEGIN.length, end).trim() !== renderStatusBlock(quality)) {
      errors.push(`${STATUS_DOC}: the quality block drifted from ${QUALITY_FILE} — a hand-edited status is not a status; run pnpm quality:report`);
    }
  }

  // --- (c) the mirrors agree with their sources --------------------------------
  for (const [label, file, exportName, value] of [
    ["static.flows", FLOWS, "flowCases", quality.static?.flows],
    ["static.contractCases", CONTRACT_CASES, "contractCases", quality.static?.contractCases],
  ]) {
    const counted = caseCount(file, exportName);
    if (counted === null) {
      errors.push(`${file} is missing or no longer exports ${exportName} — nothing backs the count the report claims`);
    } else if (value !== counted) {
      errors.push(
        `${QUALITY_FILE}: ${label} says ${JSON.stringify(value)} but ${file} carries ${counted} case(s) — rerun pnpm quality:report`,
      );
    }
  }

  const chain = verifyChain();
  if (JSON.stringify(quality.gates?.chain) !== JSON.stringify(chain)) {
    errors.push(
      `${QUALITY_FILE}: gates.chain disagrees with the package.json verify chain — ` +
        `the chain is ${chain.join(" → ")}; rerun pnpm quality:report`,
    );
  } else if (quality.gates?.count !== chain.length) {
    errors.push(`${QUALITY_FILE}: gates.count says ${JSON.stringify(quality.gates?.count)} but the chain has ${chain.length} gates`);
  }
}

gateResult(
  "status",
  `status:verify: ${STATUS_DOC} ≡ ${QUALITY_FILE} ≡ the registries ` +
    `(${quality?.static?.flows ?? 0} flow case(s), ${quality?.static?.contractCases ?? 0} contract case(s), ` +
    `${quality?.gates?.count ?? 0} gates)`,
  errors,
);
